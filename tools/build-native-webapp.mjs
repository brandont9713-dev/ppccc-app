import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");

let html = read("public/index.html");
const css = read("public/styles.css");
const js = read("public/app.js");
const eventsJson = read("public/events.generated.json");

const nativePrelude = `<script>
(function () {
  document.documentElement.dataset.platform = "ios";
  document.documentElement.dataset.preview = "compare";
  document.documentElement.dataset.nativeApp = "true";

  var memoryStore = {};
  try {
    var testKey = "__ppccc_storage_test__";
    window.localStorage.setItem(testKey, testKey);
    window.localStorage.removeItem(testKey);
  } catch (error) {
    Object.defineProperty(window, "localStorage", {
      configurable: true,
      value: {
        getItem: function (key) { return Object.prototype.hasOwnProperty.call(memoryStore, key) ? memoryStore[key] : null; },
        setItem: function (key, value) { memoryStore[key] = String(value); },
        removeItem: function (key) { delete memoryStore[key]; },
        clear: function () { memoryStore = {}; }
      }
    });
  }

  window.__PPCCC_GENERATED_EVENTS__ = ${eventsJson};
  var nativeFetch = window.fetch ? window.fetch.bind(window) : null;
  window.fetch = function (resource, options) {
    var url = typeof resource === "string" ? resource : (resource && resource.url) || "";
    if (url.indexOf("events.generated.json") !== -1) {
      return Promise.resolve({
        ok: true,
        status: 200,
        json: function () { return Promise.resolve(window.__PPCCC_GENERATED_EVENTS__); },
        text: function () { return Promise.resolve(JSON.stringify(window.__PPCCC_GENERATED_EVENTS__)); }
      });
    }
    return nativeFetch ? nativeFetch(resource, options) : Promise.reject(new Error("Fetch unavailable"));
  };
})();
</script>`;

html = html
  .replace(/<link rel="manifest"[^>]*>\s*/g, "")
  .replace(/<link rel="icon"[^>]*>\s*/g, "")
  .replace(/<link rel="apple-touch-icon"[^>]*>\s*/g, "")
  .replace(/<link rel="stylesheet" href="styles\.css[^>]*>/, `<style>\n${css}\n</style>`)
  .replace(/<script src="app\.js[^>]*><\/script>/, `${nativePrelude}\n<script>\n${js}\n</script>`);

const output = `/* Auto-generated by tools/build-native-webapp.mjs. Do not edit by hand. */\nexport const webAppHtml = ${JSON.stringify(html)};\n`;

fs.mkdirSync(path.join(root, "native-app", "src"), { recursive: true });
fs.writeFileSync(path.join(root, "native-app", "src", "webAppHtml.ts"), output);
console.log(`generated native-app/src/webAppHtml.ts (${output.length} bytes)`);
